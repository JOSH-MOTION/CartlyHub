export const getFlattenedCategories = () => {
  const flatCategories = [];
  rawCategories.forEach(main => {
    // Top-level categories
    flatCategories.push({
      id: main.id,
      name: main.name,
      level: 1
    });

    if (main.subcategories) {
      main.subcategories.forEach(sub => {
        // Create unique ID for subcategory
        const subId = `${main.id}_${sub.name.toLowerCase().replace(/[^a-z0-9]/g, '_')}`;
        flatCategories.push({
          id: subId,
          name: sub.name,
          parentId: main.id,
          level: 2
        });

        if (sub.subcategories) {
          sub.subcategories.forEach(subsub => {
            // Create unique ID for sub-subcategory
            const subsubId = `${subId}_${subsub.toLowerCase().replace(/[^a-z0-9]/g, '_')}`;
            flatCategories.push({
              id: subsubId,
              name: subsub,
              parentId: subId,
              level: 3
            });
          });
        }
      });
    }
  });

  return flatCategories;
};
